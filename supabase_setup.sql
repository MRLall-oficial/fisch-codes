-- Execute este SQL no SQL Editor do Supabase.
create table if not exists public.codes (
  id bigint generated by default as identity primary key,
  code text not null unique,
  reward text not null default '',
  status text not null default 'active' check (status in ('active','expired')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.codes enable row level security;

-- Qualquer visitante pode VER os códigos.
create policy "Public can read codes"
on public.codes for select
to anon, authenticated
using (true);

-- Somente usuários autenticados podem adicionar, editar e excluir.
create policy "Authenticated users can insert codes"
on public.codes for insert
to authenticated
with check (true);

create policy "Authenticated users can update codes"
on public.codes for update
to authenticated
using (true)
with check (true);

create policy "Authenticated users can delete codes"
on public.codes for delete
to authenticated
using (true);

